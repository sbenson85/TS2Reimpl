"""Generates tests/fx_d3d9.h: drawfx slot tables of the Direct3D 9 interfaces, from the Windows SDK's d3d9.h.

The game's Direct3D code calls a COM device: `__stdcall` methods with `this` as the first stack argument. drawfx fakes of
these interfaces (Iface::com) log every call with the method's name and its arguments normalised by kind, so that both
sides of a difftest (the original and ours) can be compared call for call. This script reads the slot order, the names
and the argument lists from d3d9.h (every interface block lists its inherited methods too) and picks the argument kinds:

  float                          f
  CONST D3DMATRIX *              F16      CONST D3DMATERIAL9 *  F17
  CONST D3DVIEWPORT9 *           W6       CONST D3DLIGHT9 *     W26
  CONST RECT * / CONST POINT *   r / p    SetClipPlane's CONST float *  F4
  shader constants (CONST float/int/BOOL * followed by the count)  @<count argument>x<words per count>
  Clear's CONST D3DRECT * (the count is argument 0)                 @0x4
  any other pointer, REFIID / REFGUID     a (a strict pointer: fakes, registered ranges, heap blocks, the stack, the
                                          images; anything else fails the test)
  anything else (DWORD, UINT, BOOL, enums, D3DCOLOR, handles)       u (data, as it is)
Every argument gets a kind from its declared type: none is left 'i' (undeclared), and none is guessed from its value.

Usage: tools/py -I tools/d3dslots.py [--sdk <path of d3d9.h>] [--out tests/fx_d3d9.h] [--check]
--check exits 1 when the header on disk differs from what would be generated.
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The interfaces the game uses (not the 9Ex / video ones).
INTERFACES = [
    "IDirect3D9", "IDirect3DDevice9", "IDirect3DStateBlock9", "IDirect3DSwapChain9", "IDirect3DResource9",
    "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DBaseTexture9",
    "IDirect3DTexture9", "IDirect3DVolumeTexture9", "IDirect3DCubeTexture9", "IDirect3DVertexBuffer9",
    "IDirect3DIndexBuffer9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DQuery9",
]

FIXED = {
    "D3DMATRIX": "F16", "D3DMATERIAL9": "F17", "D3DVIEWPORT9": "W6", "D3DLIGHT9": "W26", "RECT": "r", "POINT": "p",
}
# C++ references (pointers in the call): the IID / GUID arguments.
REFERENCES = {"REFIID", "REFGUID"}
# Constant arrays whose length is another argument: (method prefix, words per counted element).
COUNTED = {"ShaderConstantF": 4, "ShaderConstantI": 4, "ShaderConstantB": 1}


def find_sdk():
    pattern = r"C:\Program Files (x86)\Windows Kits\10\Include\*\shared\d3d9.h"
    found = sorted(glob.glob(pattern))
    if not found:
        sys.exit("d3dslots: no d3d9.h under the Windows 10 SDK (pass --sdk)")
    return found[-1]


METHOD = re.compile(r"STDMETHOD(_)?\(\s*(?:([^,]+?)\s*,\s*)?(\w+)\s*\)\s*\((.*)\)\s*PURE;")


def parse(text):
    """{interface: [(name, return type, [argument declarations])]} for every DECLARE_INTERFACE_ block."""
    out = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\((\w+),\s*\w+\)\s*\{(.*?)\n\};", text, re.S):
        methods = []
        for line in m.group(2).splitlines():
            mm = METHOD.search(line)
            if not mm:
                continue
            ret = (mm.group(2) or "HRESULT").strip()
            args = mm.group(4).strip()
            args = re.sub(r"^THIS_?\s*", "", args)
            decls = [a.strip() for a in args.split(",") if a.strip()]
            methods.append((mm.group(3), ret, decls))
        out[m.group(1)] = methods
    return out


def kinds(method, decls):
    out = []
    for i, d in enumerate(decls):
        const = d.startswith("CONST ") or d.startswith("const ")
        base = re.sub(r"^(CONST|const)\s+", "", d)
        typ = re.split(r"[\s*]", base, 1)[0]
        pointer = "*" in d or typ in REFERENCES
        k = "a" if pointer else "u"  # by the declared type, never by the values a test passes (tests/norm_words.h)
        if typ == "float" and not pointer:
            k = "f"
        elif const and pointer and typ in FIXED:
            k = FIXED[typ]
        elif const and pointer and method == "SetClipPlane":
            k = "F4"
        elif const and pointer and method == "Clear" and typ == "D3DRECT":
            k = "@0x4"
        elif const and pointer:
            for suffix, per in COUNTED.items():
                if method.endswith(suffix) and i + 1 < len(decls):
                    k = f"@{i + 1}x{per}"
        out.append(k)
    return "".join(out)


def generate(sdk):
    with open(sdk, encoding="latin-1") as f:
        parsed = parse(f.read())
    lines = [
        "#pragma once",
        f"// Generated by tools/d3dslots.py from the Windows SDK's d3d9.h ({os.path.basename(os.path.dirname(os.path.dirname(sdk)))}): do not edit.",
        "// Slot order, names and argument kinds of the Direct3D 9 interfaces, for drawfx COM fakes (tests/d3dfx.h).",
        '#include "drawfx_core.h"',
        "",
        "namespace fx_d3d9 {",
        "using drawfx::Ret;",
        "using drawfx::Slot;",
        "inline constexpr const char *kDeclare = \"in tools/d3dslots.py (by the argument's type in d3d9.h), then regenerate tests/fx_d3d9.h\";",
        "",
    ]
    for name in INTERFACES:
        methods = parsed.get(name)
        if not methods:
            sys.exit(f"d3dslots: {name} not found in {sdk}")
        lines.append(f"// {name}: {len(methods)} slots")
        lines.append(f"inline constexpr Slot k{name}Slots[] = {{")
        for slot, (method, ret, decls) in enumerate(methods):
            r = "Ret::Float" if ret == "float" else "Ret::Int"
            lines.append(f'    {{{len(decls)}, {r}, true, "{method}", "{kinds(method, decls)}"}}, // {slot}')
        lines.append("};")
        lines.append(f'inline constexpr drawfx::Iface {name}{{"{name}", {len(methods)}, k{name}Slots, true, kDeclare}};')
        lines.append("")
    # Slot numbers by name for the device, so tests program results by name.
    lines.append("// IDirect3DDevice9 slot numbers.")
    lines.append("namespace dev {")
    for slot, (method, _, _) in enumerate(parsed["IDirect3DDevice9"]):
        lines.append(f"inline constexpr unsigned {method} = {slot};")
    lines.append("} // namespace dev")
    lines.append("")
    lines.append("} // namespace fx_d3d9")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", default=None)
    ap.add_argument("--out", default=os.path.join(ROOT, "tests", "fx_d3d9.h"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = generate(a.sdk or find_sdk())
    if a.check:
        with open(a.out, encoding="utf-8") as f:
            same = f.read() == text
        print("fx_d3d9.h up to date" if same else "fx_d3d9.h differs from d3d9.h: regenerate")
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
