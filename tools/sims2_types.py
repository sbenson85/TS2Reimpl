# Non-package files in the user-data folder, matched on the path relative to the root
# (forward slashes, lower case). First match wins.
FILE_RULES = [
    ("thumbnails/", T, "thumbnail images regenerated by the game"),
    ("/thumbnails/", T, "thumbnail images regenerated by the game"),
    (".png", T, "neighbourhood/lot preview image, regenerated by the game"),
    ("logs/", T, "diagnostic logs"),
    (".cache", T, "game-managed cache files"),
    (".log", T, "diagnostic logs"),
]


def type_info(t):
    return TYPES.get(t, ("0x%08X" % t, U, ""))


def type_name(t):
    return type_info(t)[0]


def type_class(t):
    return type_info(t)[1]


def file_class(relpath):
    p = relpath.replace("\\", "/").lower()
    for pat, cls, why in FILE_RULES:
        if pat.endswith("/"):
            if p.startswith(pat) or ("/" + pat) in p:
                return cls, why
        elif pat.startswith("/"):
            if pat in p:
                return cls, why
        elif p.endswith(pat):
            return cls, why
    return U, ""


def class_counts(seen=None):
    """Count table entries per class (optionally only ids present in `seen`)."""
    out = {P: 0, T: 0, U: 0}
    for t, (_, c, _) in TYPES.items():
        if seen is None or t in seen:
            out[c] += 1
    return out


# Field exclusions: byte ranges inside a resource that are known not to carry state, each with the
# reason and the evidence that established it. A resource whose differences all fall inside its
# exclusions is reported as `excluded` (with the reasons); otherwise the excluded bytes are masked
# and the rest is reported as usual. Add a rule only once the field's meaning is established.
def _after_magic(magic, skip, length):
    def locate(data):
        out = []
        i = data.find(magic)
        if i >= 0:
            out.append((i + skip, i + skip + length))
        return out
    return locate


FIELD_EXCLUSIONS = {
    0xACE46235: [(
        _after_magic(b"\x35\x62\xe4\xac\x01\x00\x00\x00", 8, 4),
        "uninitialised memory: nTSWorld::cProxyManager's serialisable maps (0x18-byte objects built "
        "in cProxyManager slot 3, 0x81aeb0..0x81af0f) never set their field at +0x14; Write "
        "(0x81d0f0 / 0x81d190) stores it after the type id and version 1, Read (0x81bd90) only "
        "reads it back. Seen as heap-like values (0x06accbf4), 0x6c, 'flag' and 0x0e/0 (2026-10-11).",
    )],
}


def excluded_ranges(type_id, data):
    """[(lo, hi, reason)] of excluded bytes in one resource's content."""
    out = []
    for locate, reason in FIELD_EXCLUSIONS.get(type_id, []):
        out.extend((lo, hi, reason) for lo, hi in locate(data))
    return out
